const FA = "۰۱۲۳۴۵۶۷۸۹";
/** Latin digits → Persian digits, with thousands separators for big numbers. */
export function fa(n) {
  const s = typeof n === "number" ? (Math.abs(n) >= 10000 ? Math.round(n).toLocaleString("en-US") : String(Math.round(n))) : String(n);
  return s.replace(/\d/g, (d) => FA[d]).replace(/,/g, "٬");
}
